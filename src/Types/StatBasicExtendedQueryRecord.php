<?php

namespace Payabli\Types;

use Payabli\Core\Json\JsonSerializableType;
use Payabli\Core\Json\JsonProperty;

class StatBasicExtendedQueryRecord extends JsonSerializableType
{
    /**
     * @var string $statX The time bucket for this row, formatted according to the query's `freq` (for example, `2025-11` for a monthly bucket). The response returns one object per bucket across the requested range.
     */
    #[JsonProperty('statX')]
    public string $statX;

    /**
     * @var int $outCustomers Cumulative number of vendors, as a running total through the end of this bucket rather than a per-bucket count. On the payout (money out) side, "customers" are vendors.
     */
    #[JsonProperty('outCustomers')]
    public int $outCustomers;

    /**
     * @var int $outNewCustomers Number of vendors created during this bucket, scoped to the paypoint (`level` 2) or organization (`level` 0).
     */
    #[JsonProperty('outNewCustomers')]
    public int $outNewCustomers;

    /**
     * @var int $outTransactions Count of payout (money out) transactions. The payout method counts (`outCardTransactions`, `outVCardTransactions`, `outACHTransactions`, `outCheckTransactions`, `outPendingMethodTransactions`, `outRTPTransactions`, `outWireTransactions`) are mutually exclusive and together account for this total.
     */
    #[JsonProperty('outTransactions')]
    public int $outTransactions;

    /**
     * @var int $outSubscriptionsPaid Count of payout transactions generated by a recurring schedule.
     */
    #[JsonProperty('outSubscriptionsPaid')]
    public int $outSubscriptionsPaid;

    /**
     * @var int $outCardTransactions Count of payout transactions sent by pCard.
     */
    #[JsonProperty('outCardTransactions')]
    public int $outCardTransactions;

    /**
     * @var int $outVCardTransactions Count of payout transactions sent by virtual card (vCard).
     */
    #[JsonProperty('outVCardTransactions')]
    public int $outVCardTransactions;

    /**
     * @var int $outAchTransactions Count of payout transactions sent by ACH.
     */
    #[JsonProperty('outACHTransactions')]
    public int $outAchTransactions;

    /**
     * @var int $outCheckTransactions Count of payout transactions sent by check.
     */
    #[JsonProperty('outCheckTransactions')]
    public int $outCheckTransactions;

    /**
     * @var int $outPendingMethodTransactions Count of payout transactions held as Managed Payables, where the payout method isn't assigned yet.
     */
    #[JsonProperty('outPendingMethodTransactions')]
    public int $outPendingMethodTransactions;

    /**
     * @var int $outRtpTransactions Count of payout transactions sent by real-time payments (RTP).
     */
    #[JsonProperty('outRTPTransactions')]
    public int $outRtpTransactions;

    /**
     * @var float $outRtpVolume Total value of RTP payouts, net of fees.
     */
    #[JsonProperty('outRTPVolume')]
    public float $outRtpVolume;

    /**
     * @var int $outWireTransactions Count of payout transactions sent by wire.
     */
    #[JsonProperty('outWireTransactions')]
    public int $outWireTransactions;

    /**
     * @var float $outWireVolume Total value of wire payouts, net of fees.
     */
    #[JsonProperty('outWireVolume')]
    public float $outWireVolume;

    /**
     * @var float $outTransactionsVolume Total payout value, net of fees.
     */
    #[JsonProperty('outTransactionsVolume')]
    public float $outTransactionsVolume;

    /**
     * @var float $outSubscriptionsPaidVolume Total value of recurring payouts, net of fees.
     */
    #[JsonProperty('outSubscriptionsPaidVolume')]
    public float $outSubscriptionsPaidVolume;

    /**
     * @var float $outCardVolume Total value of pCard payouts, net of fees.
     */
    #[JsonProperty('outCardVolume')]
    public float $outCardVolume;

    /**
     * @var float $outVCardVolume Total value of vCard payouts, net of fees.
     */
    #[JsonProperty('outVCardVolume')]
    public float $outVCardVolume;

    /**
     * @var float $outAchVolume Total value of ACH payouts, net of fees.
     */
    #[JsonProperty('outACHVolume')]
    public float $outAchVolume;

    /**
     * @var float $outCheckVolume Total value of check payouts, net of fees.
     */
    #[JsonProperty('outCheckVolume')]
    public float $outCheckVolume;

    /**
     * @var float $outPendingMethodVolume Total value of Managed Payables payouts, net of fees.
     */
    #[JsonProperty('outPendingMethodVolume')]
    public float $outPendingMethodVolume;

    /**
     * @var int $inTransactions Count of approved inbound (money in) transactions. This counts approved transactions only and leaves out declines. The payment method counts (`inCardTransactions`, `inACHTransactions`, `inCheckTransactions`, `inCashTransactions`, `inWalletTransactions`) are mutually exclusive and sum to this total.
     */
    #[JsonProperty('inTransactions')]
    public int $inTransactions;

    /**
     * @var int $inSubscriptionsPaid Count of approved inbound transactions charged by a recurring schedule. This is a subset of `inTransactions`, not an amount to add on top of it.
     */
    #[JsonProperty('inSubscriptionsPaid')]
    public int $inSubscriptionsPaid;

    /**
     * @var int $inCustomers Cumulative number of customers, as a running total through the end of this bucket rather than a per-bucket count.
     */
    #[JsonProperty('inCustomers')]
    public int $inCustomers;

    /**
     * @var int $inNewCustomers Number of customers created during this bucket, scoped to the paypoint (`level` 2) or organization (`level` 0).
     */
    #[JsonProperty('inNewCustomers')]
    public int $inNewCustomers;

    /**
     * @var int $inCardTransactions Count of approved inbound card transactions, including card, cloud device, and in-person device payments.
     */
    #[JsonProperty('inCardTransactions')]
    public int $inCardTransactions;

    /**
     * @var int $inAchTransactions Count of approved inbound ACH transactions.
     */
    #[JsonProperty('inACHTransactions')]
    public int $inAchTransactions;

    /**
     * @var int $inCheckTransactions Count of approved inbound check transactions.
     */
    #[JsonProperty('inCheckTransactions')]
    public int $inCheckTransactions;

    /**
     * @var int $inCashTransactions Count of approved inbound cash transactions.
     */
    #[JsonProperty('inCashTransactions')]
    public int $inCashTransactions;

    /**
     * @var int $inWalletTransactions Count of approved inbound digital wallet transactions.
     */
    #[JsonProperty('inWalletTransactions')]
    public int $inWalletTransactions;

    /**
     * @var int $inCardChargeBacks Count of card chargebacks recorded. Tracked separately from `inACHReturns`.
     */
    #[JsonProperty('inCardChargeBacks')]
    public int $inCardChargeBacks;

    /**
     * @var int $inAchReturns Count of ACH returns recorded.
     */
    #[JsonProperty('inACHReturns')]
    public int $inAchReturns;

    /**
     * @var float $inTransactionsVolume Total approved inbound value, net of fees.
     */
    #[JsonProperty('inTransactionsVolume')]
    public float $inTransactionsVolume;

    /**
     * @var float $inSubscriptionsPaidVolume Total value of approved recurring inbound transactions, net of fees.
     */
    #[JsonProperty('inSubscriptionsPaidVolume')]
    public float $inSubscriptionsPaidVolume;

    /**
     * @var float $inCardVolume Total approved card value, net of fees.
     */
    #[JsonProperty('inCardVolume')]
    public float $inCardVolume;

    /**
     * @var float $inAchVolume Total approved ACH value, net of fees.
     */
    #[JsonProperty('inACHVolume')]
    public float $inAchVolume;

    /**
     * @var float $inCheckVolume Total approved check value, net of fees.
     */
    #[JsonProperty('inCheckVolume')]
    public float $inCheckVolume;

    /**
     * @var float $inCashVolume Total approved cash value, net of fees.
     */
    #[JsonProperty('inCashVolume')]
    public float $inCashVolume;

    /**
     * @var float $inWalletVolume Total approved digital wallet value, net of fees.
     */
    #[JsonProperty('inWalletVolume')]
    public float $inWalletVolume;

    /**
     * @var float $inCardChargeBackVolume Total value of card chargebacks.
     */
    #[JsonProperty('inCardChargeBackVolume')]
    public float $inCardChargeBackVolume;

    /**
     * @var float $inAchReturnsVolume Total value of ACH returns.
     */
    #[JsonProperty('inACHReturnsVolume')]
    public float $inAchReturnsVolume;

    /**
     * @param array{
     *   statX: string,
     *   outCustomers: int,
     *   outNewCustomers: int,
     *   outTransactions: int,
     *   outSubscriptionsPaid: int,
     *   outCardTransactions: int,
     *   outVCardTransactions: int,
     *   outAchTransactions: int,
     *   outCheckTransactions: int,
     *   outPendingMethodTransactions: int,
     *   outRtpTransactions: int,
     *   outRtpVolume: float,
     *   outWireTransactions: int,
     *   outWireVolume: float,
     *   outTransactionsVolume: float,
     *   outSubscriptionsPaidVolume: float,
     *   outCardVolume: float,
     *   outVCardVolume: float,
     *   outAchVolume: float,
     *   outCheckVolume: float,
     *   outPendingMethodVolume: float,
     *   inTransactions: int,
     *   inSubscriptionsPaid: int,
     *   inCustomers: int,
     *   inNewCustomers: int,
     *   inCardTransactions: int,
     *   inAchTransactions: int,
     *   inCheckTransactions: int,
     *   inCashTransactions: int,
     *   inWalletTransactions: int,
     *   inCardChargeBacks: int,
     *   inAchReturns: int,
     *   inTransactionsVolume: float,
     *   inSubscriptionsPaidVolume: float,
     *   inCardVolume: float,
     *   inAchVolume: float,
     *   inCheckVolume: float,
     *   inCashVolume: float,
     *   inWalletVolume: float,
     *   inCardChargeBackVolume: float,
     *   inAchReturnsVolume: float,
     * } $values
     */
    public function __construct(
        array $values,
    ) {
        $this->statX = $values['statX'];
        $this->outCustomers = $values['outCustomers'];
        $this->outNewCustomers = $values['outNewCustomers'];
        $this->outTransactions = $values['outTransactions'];
        $this->outSubscriptionsPaid = $values['outSubscriptionsPaid'];
        $this->outCardTransactions = $values['outCardTransactions'];
        $this->outVCardTransactions = $values['outVCardTransactions'];
        $this->outAchTransactions = $values['outAchTransactions'];
        $this->outCheckTransactions = $values['outCheckTransactions'];
        $this->outPendingMethodTransactions = $values['outPendingMethodTransactions'];
        $this->outRtpTransactions = $values['outRtpTransactions'];
        $this->outRtpVolume = $values['outRtpVolume'];
        $this->outWireTransactions = $values['outWireTransactions'];
        $this->outWireVolume = $values['outWireVolume'];
        $this->outTransactionsVolume = $values['outTransactionsVolume'];
        $this->outSubscriptionsPaidVolume = $values['outSubscriptionsPaidVolume'];
        $this->outCardVolume = $values['outCardVolume'];
        $this->outVCardVolume = $values['outVCardVolume'];
        $this->outAchVolume = $values['outAchVolume'];
        $this->outCheckVolume = $values['outCheckVolume'];
        $this->outPendingMethodVolume = $values['outPendingMethodVolume'];
        $this->inTransactions = $values['inTransactions'];
        $this->inSubscriptionsPaid = $values['inSubscriptionsPaid'];
        $this->inCustomers = $values['inCustomers'];
        $this->inNewCustomers = $values['inNewCustomers'];
        $this->inCardTransactions = $values['inCardTransactions'];
        $this->inAchTransactions = $values['inAchTransactions'];
        $this->inCheckTransactions = $values['inCheckTransactions'];
        $this->inCashTransactions = $values['inCashTransactions'];
        $this->inWalletTransactions = $values['inWalletTransactions'];
        $this->inCardChargeBacks = $values['inCardChargeBacks'];
        $this->inAchReturns = $values['inAchReturns'];
        $this->inTransactionsVolume = $values['inTransactionsVolume'];
        $this->inSubscriptionsPaidVolume = $values['inSubscriptionsPaidVolume'];
        $this->inCardVolume = $values['inCardVolume'];
        $this->inAchVolume = $values['inAchVolume'];
        $this->inCheckVolume = $values['inCheckVolume'];
        $this->inCashVolume = $values['inCashVolume'];
        $this->inWalletVolume = $values['inWalletVolume'];
        $this->inCardChargeBackVolume = $values['inCardChargeBackVolume'];
        $this->inAchReturnsVolume = $values['inAchReturnsVolume'];
    }

    /**
     * @return string
     */
    public function __toString(): string
    {
        return $this->toJson();
    }
}
